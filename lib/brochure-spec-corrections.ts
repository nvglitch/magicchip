export function applyBrochureSpecCorrections<T extends { id: string; specs: { label: string; value: string }[] }>(item: T): T {
  const changes = brochureSpecCorrections[item.id];
  if (!changes) return item;
  return { ...item, specs: [...item.specs.filter(spec => !changes.some(change => change.label === spec.label)), ...changes] };
}
